// Helper to resolve image paths across root and subfolders
function getImagePath(path) {
  if (!path) return '';
  if (path.startsWith('http://') || path.startsWith('https://') || path.startsWith('data:')) return path;
  const isSubfolder = window.location.pathname.includes('/pages/') || window.location.pathname.endsWith('/pages');
  if (isSubfolder && path.startsWith('assets/')) {
    return '../' + path;
  }
  return path;
}

// Category Page Rendering & Sorting System
function setupCategoryPage(type) {
  const gridContainer = document.getElementById(`${type}-product-grid`);
  if (!gridContainer) return;

  const categoryBtns = document.querySelectorAll(`.${type}-category-btn`);
  const sortWrapper = document.getElementById(`${type}-sort-wrapper`);
  const sortTrigger = document.getElementById(`${type}-sort-trigger`);
  const sortDropdown = document.getElementById(`${type}-sort-dropdown`);
  const sortOptions = document.querySelectorAll(`.${type}-sort-option`);
  const loadMoreBtn = document.getElementById(`${type}-load-more-btn`);
  const countDisplay = document.getElementById(`${type}-count`);

  let activeCategory = 'all';
  let activeSort = 'recommended';
  let displayedCount = 8;
  const INITIAL_BATCH = 8;
  const LOAD_MORE_BATCH = 4;

  function getFilteredProducts() {
    let list = [];
    if (type === 'wishlist') {
      const savedIds = window.getWishlist ? window.getWishlist() : [];
      list = window.PRODUCTS.filter(p => savedIds.includes(p.id));
    } else if (type === 'sales' || type === 'sale') {
      list = window.PRODUCTS.filter(p => p.onSale === true || (p.oldPrice && p.oldPrice > p.price));
    } else {
      list = window.PRODUCTS.filter(p => p.type === type);
    }

    if (activeCategory === 'clothes') {
      list = list.filter(p => p.category === 'clothes');
    } else if (activeCategory === 'shoes-accessories') {
      list = list.filter(p => p.category === 'shoes-accessories' || p.category === 'shoes' || p.category === 'accessories');
    }

    if (activeSort === 'newest') {
      list.sort((a, b) => new Date(b.dateAdded || 0) - new Date(a.dateAdded || 0));
    } else if (activeSort === 'price-low') {
      list.sort((a, b) => a.price - b.price);
    } else if (activeSort === 'price-high') {
      list.sort((a, b) => b.price - a.price);
    } else if (activeSort === 'biggest-discount') {
      list.sort((a, b) => {
        const discA = a.oldPrice ? ((a.oldPrice - a.price) / a.oldPrice) : 0;
        const discB = b.oldPrice ? ((b.oldPrice - b.price) / b.oldPrice) : 0;
        return discB - discA;
      });
    }

    return list;
  }

  function renderGrid() {
    const allFiltered = getFilteredProducts();
    const visibleProducts = allFiltered.slice(0, displayedCount);

    if (countDisplay) {
      countDisplay.textContent = `${allFiltered.length} ITEMS`;
    }

    if (allFiltered.length === 0) {
      if (type === 'wishlist') {
        gridContainer.innerHTML = `
          <div class="wishlist-empty-box">
            <div class="wishlist-empty__icon"><i class="fa-regular fa-heart"></i></div>
            <div class="wishlist-empty__title">YOUR WISHLIST IS EMPTY</div>
          </div>
        `;
      } else {
        gridContainer.innerHTML = `<div class="${type}-empty-state">No products found in this category.</div>`;
      }
      if (loadMoreBtn) loadMoreBtn.classList.add('hidden');
      return;
    }

    gridContainer.innerHTML = visibleProducts.map(product => {
      const front = getImagePath(product.image || product.frontImage || product.front);
      const currency = product.currency || 'EGP';
      const formattedPrice = `${currency} ${product.price.toLocaleString()}`;

      const oldPriceHtml = (product.oldPrice && product.oldPrice > product.price)
        ? `<span class="${type}-card__old-price">${currency} ${product.oldPrice.toLocaleString()}</span>`
        : '';

      const discountBadgeHtml = (product.oldPrice && product.oldPrice > product.price)
        ? `<span class="card-discount-badge">-${Math.round(((product.oldPrice - product.price) / product.oldPrice) * 100)}%</span>`
        : '';

      const colorsHtml = (product.colors && product.colors.length > 0)
        ? `<div class="${type}-card__colors">
             ${product.colors.map(c => `<span class="${type}-card__color-dot" style="background-color: ${c};"></span>`).join('')}
           </div>`
        : `<div class="${type}-card__colors"></div>`;

      const isSaved = window.isInWishlist ? window.isInWishlist(product.id) : false;
      const heartIconClass = isSaved ? 'fa-solid fa-heart' : 'fa-regular fa-heart';
      const activeClass = isSaved ? 'active' : '';

      return `
        <div class="${type}-card" data-id="${product.id}">
          <div class="${type}-card__img-wrap">
            ${discountBadgeHtml}
            <img src="${front}" alt="${product.name}" class="${type}-card__img-front" loading="lazy">
            <button type="button" class="${type}-card__wishlist ${activeClass}" aria-label="Add to Wishlist" data-id="${product.id}">
              <i class="${heartIconClass}"></i>
            </button>
          </div>
          <div class="${type}-card__info">
            ${colorsHtml}
            <h3 class="${type}-card__name">${product.name}</h3>
            <div class="${type}-card__price-row">
              <span class="${type}-card__price">${formattedPrice}</span>
              ${oldPriceHtml}
            </div>
          </div>
        </div>
      `;
    }).join('');

    if (loadMoreBtn) {
      if (displayedCount >= allFiltered.length) {
        loadMoreBtn.classList.add('hidden');
      } else {
        loadMoreBtn.classList.remove('hidden');
      }
    }

    // Attach Wishlist heart click listeners & Card detail click listeners
    document.querySelectorAll(`.${type}-card`).forEach(card => {
      card.style.cursor = 'pointer';
      card.addEventListener('click', (e) => {
        if (e.target.closest(`.${type}-card__wishlist`)) return;
        const id = card.dataset.id;
        const isInsidePages = window.location.pathname.toLowerCase().includes('/pages/');
        const targetUrl = isInsidePages ? `product.html?id=${id}` : `pages/product.html?id=${id}`;
        window.location.href = targetUrl;
      });
    });

    document.querySelectorAll(`.${type}-card__wishlist`).forEach(btn => {
      btn.addEventListener('click', (e) => {
        e.preventDefault();
        e.stopPropagation();
        const card = btn.closest(`.${type}-card`);
        const id = card ? card.dataset.id : btn.dataset.id;
        if (!id) return;

        if (window.toggleWishlist) {
          window.toggleWishlist(id);
        } else {
          btn.classList.toggle('active');
        }

        if (type === 'wishlist') {
          renderGrid();
        }
      });
    });
  }

  categoryBtns.forEach(btn => {
    btn.addEventListener('click', () => {
      categoryBtns.forEach(b => b.classList.remove('active'));
      btn.classList.add('active');
      activeCategory = btn.dataset.category || 'all';
      displayedCount = INITIAL_BATCH;
      renderGrid();
    });
  });

  if (sortTrigger && sortDropdown) {
    sortTrigger.addEventListener('click', (e) => {
      e.stopPropagation();
      sortDropdown.classList.toggle('show');
      sortWrapper.classList.toggle('active');
    });

    document.addEventListener('click', (e) => {
      if (!sortWrapper.contains(e.target)) {
        sortDropdown.classList.remove('show');
        sortWrapper.classList.remove('active');
      }
    });
  }

  sortOptions.forEach(opt => {
    opt.addEventListener('click', () => {
      sortOptions.forEach(o => o.classList.remove('active'));
      opt.classList.add('active');
      activeSort = opt.dataset.sort || 'recommended';
      sortDropdown.classList.remove('show');
      sortWrapper.classList.remove('active');
      displayedCount = INITIAL_BATCH;
      renderGrid();
    });
  });

  if (loadMoreBtn) {
    loadMoreBtn.addEventListener('click', () => {
      displayedCount += LOAD_MORE_BATCH;
      renderGrid();
    });
  }

  renderGrid();
}

document.addEventListener('DOMContentLoaded', () => {
  setupCategoryPage('men');
  setupCategoryPage('women');
  setupCategoryPage('kids');
  setupCategoryPage('sales');
  setupCategoryPage('wishlist');
});

// Color Name Helper
function getColorName(hex) {
  if (!hex) return '';
  const h = hex.toUpperCase();
  if (['#111111', '#000000', '#1A1A1A', '#222222'].includes(h)) return 'Black';
  if (['#EAEAEA', '#FFFFFF', '#E5E5E5', '#FAF7F0', '#F4F1EA'].includes(h)) return 'White / Cream';
  if (['#7D7D7D', '#999999', '#333333', '#8E8E93', '#3A3A3A', '#708090'].includes(h)) return 'Grey';
  if (['#7B90A8', '#2C3E50', '#4A5568', '#2B2E34', '#1A2530', '#1B263B', '#5D8AA8', '#4A6B82'].includes(h)) return 'Navy / Blue';
  if (['#C4B7A6', '#5C4033', '#B8C4D0', '#A89F91', '#C19A6B', '#DCD0C0', '#8B5A2B', '#783F04', '#3D2B1F', '#4B3621'].includes(h)) return 'Beige / Brown';
  if (['#2F3331', '#7A8B7B', '#556B2F', '#0F4C3A', '#2F5233'].includes(h)) return 'Olive / Green';
  if (['#D4AF37', '#E1AD01'].includes(h)) return 'Gold / Mustard';
  if (['#DE5D83', '#5C1D24', '#722F37', '#9B1C1C', '#A0522D'].includes(h)) return 'Burgundy / Rose';
  return 'Color';
}

// Product Details Page Initialization
function initProductDetailsPage() {
  const pageContainer = document.getElementById('moodk-product-details-page');
  if (!pageContainer) return;

  const urlParams = new URLSearchParams(window.location.search);
  const productId = urlParams.get('id') || 'm1';

  const product = window.PRODUCTS.find(p => p.id === productId) || window.PRODUCTS[0];
  if (!product) return;

  // DOM elements
  const nameEl = document.getElementById('pd-name');
  const priceEl = document.getElementById('pd-price');
  const oldPriceEl = document.getElementById('pd-old-price');
  const saleBadgeEl = document.getElementById('pd-sale-badge');
  const tagEl = document.getElementById('pd-category-tag');
  const descEl = document.getElementById('pd-desc');
  const breadcrumbCategory = document.getElementById('breadcrumb-category');
  const breadcrumbName = document.getElementById('breadcrumb-name');
  const mainImgEl = document.getElementById('pd-main-image');
  const thumbsContainer = document.getElementById('pd-thumbs-container');
  const colorSwatchesContainer = document.getElementById('pd-color-swatches');
  const selectedColorNameEl = document.getElementById('pd-selected-color-name');
  const sizeOptionsContainer = document.getElementById('pd-size-options');
  const selectedSizeValEl = document.getElementById('pd-selected-size-val');
  const qtyValEl = document.getElementById('pd-qty-val');
  const qtyMinusBtn = document.getElementById('pd-qty-minus');
  const qtyPlusBtn = document.getElementById('pd-qty-plus');
  const alertEl = document.getElementById('pd-alert');
  const addToBasketBtn = document.getElementById('pd-add-to-basket-btn');

  // Populate product info
  if (nameEl) nameEl.textContent = product.name;
  if (breadcrumbName) breadcrumbName.textContent = product.name;

  const typeName = (product.type || 'men').toUpperCase();
  if (tagEl) tagEl.textContent = `${typeName} COLLECTION`;

  if (breadcrumbCategory) {
    breadcrumbCategory.textContent = typeName.charAt(0) + typeName.slice(1).toLowerCase();
    breadcrumbCategory.href = `${product.type || 'men'}.html`;
  }

  if (descEl && product.description) {
    descEl.textContent = product.description;
  }

  const currency = product.currency || 'EGP';
  if (priceEl) priceEl.textContent = `${currency} ${product.price.toLocaleString()}`;

  if (product.oldPrice && oldPriceEl && product.oldPrice > product.price) {
    oldPriceEl.textContent = `${currency} ${product.oldPrice.toLocaleString()}`;
    oldPriceEl.style.display = 'inline-block';
    if (saleBadgeEl) saleBadgeEl.style.display = 'inline-block';
  } else {
    if (oldPriceEl) oldPriceEl.style.display = 'none';
    if (saleBadgeEl) saleBadgeEl.style.display = 'none';
  }

  // Gallery Setup
  const mainProductImg = getImagePath(product.image || product.frontImage || product.front);

  if (mainImgEl) {
    mainImgEl.src = mainProductImg;
    mainImgEl.alt = product.name;
  }

  if (thumbsContainer) {
    thumbsContainer.style.display = 'none';
  }

  // Color Selection Logic
  let selectedColor = null;
  let selectedColorName = '';

  const colors = product.colors || [];
  const colorSection = document.getElementById('pd-color-section');

  if (colors.length > 0) {
    if (colorSection) colorSection.style.display = 'block';
    if (colorSwatchesContainer) {
      colorSwatchesContainer.innerHTML = colors.map((colorHex) => {
        const name = getColorName(colorHex);
        return `
          <button type="button" 
                  class="color-swatch-btn" 
                  style="background-color: ${colorHex};" 
                  data-hex="${colorHex}" 
                  data-name="${name}" 
                  title="${name}"
                  aria-label="Select ${name} color">
          </button>
        `;
      }).join('');

      document.querySelectorAll('.color-swatch-btn').forEach(btn => {
        btn.addEventListener('click', () => {
          document.querySelectorAll('.color-swatch-btn').forEach(b => b.classList.remove('active'));
          btn.classList.add('active');
          selectedColor = btn.dataset.hex;
          selectedColorName = btn.dataset.name;
          if (selectedColorNameEl) selectedColorNameEl.textContent = selectedColorName;
          clearProductAlert();
        });
      });
    }
  } else {
    if (colorSection) colorSection.style.display = 'none';
  }

  // Size Selection Logic
  let selectedSize = null;
  const availableSizes = (product.sizes && product.sizes.length > 0)
    ? product.sizes
    : ['XS', 'S', 'M', 'L', 'XL'];

  if (sizeOptionsContainer) {
    sizeOptionsContainer.innerHTML = availableSizes.map(sz => `
      <button type="button" class="size-btn" data-size="${sz}">${sz}</button>
    `).join('');

    document.querySelectorAll('.size-btn').forEach(btn => {
      btn.addEventListener('click', () => {
        document.querySelectorAll('.size-btn').forEach(b => b.classList.remove('active'));
        btn.classList.add('active');
        selectedSize = btn.dataset.size;
        if (selectedSizeValEl) selectedSizeValEl.textContent = selectedSize;
        clearProductAlert();
      });
    });
  }

  // Quantity Control Logic
  let currentQty = 1;
  if (qtyMinusBtn && qtyPlusBtn && qtyValEl) {
    qtyMinusBtn.addEventListener('click', () => {
      if (currentQty > 1) {
        currentQty--;
        qtyValEl.textContent = currentQty;
      }
    });

    qtyPlusBtn.addEventListener('click', () => {
      currentQty++;
      qtyValEl.textContent = currentQty;
    });
  }

  // Alert helpers
  function showProductAlert(message, type = 'error') {
    if (!alertEl) return;
    alertEl.className = `product-alert ${type}`;
    alertEl.innerHTML = `
      <i class="fa-solid ${type === 'error' ? 'fa-circle-exclamation' : 'fa-circle-check'}"></i>
      <span>${message}</span>
    `;
  }

  function clearProductAlert() {
    if (!alertEl) return;
    alertEl.className = 'product-alert';
    alertEl.innerHTML = '';
  }

  // Add to Basket Click Handler
  if (addToBasketBtn) {
    addToBasketBtn.addEventListener('click', () => {
      if (colors.length > 0 && !selectedColor) {
        showProductAlert('Please select a color before adding to basket.');
        return;
      }

      if (!selectedSize) {
        showProductAlert('Please select a size before adding to basket.');
        return;
      }

      const itemData = {
        id: product.id,
        name: product.name,
        price: product.price,
        currency: product.currency || 'EGP',
        image: product.image || product.frontImage || product.front,
        color: selectedColor || '',
        colorName: selectedColorName || '',
        size: selectedSize,
        quantity: currentQty
      };

      const loggedIn = typeof isUserLoggedIn === 'function' ? isUserLoggedIn() : false;

      if (loggedIn) {
        if (typeof addToCart === 'function') {
          addToCart(itemData);
        }
        showProductAlert(`✓ Added ${currentQty} item(s) to your basket!`, 'success');
      } else {
        localStorage.setItem('moodkPendingCartItem', JSON.stringify(itemData));
        window.location.href = 'login.html';
      }
    });
  }

  // Wishlist Button Handler on Product Details Page
  const pdWishlistBtn = document.getElementById('pd-wishlist-btn');
  if (pdWishlistBtn) {
    pdWishlistBtn.dataset.id = product.id;
    if (window.isInWishlist && window.isInWishlist(product.id)) {
      pdWishlistBtn.classList.add('active');
      const icon = pdWishlistBtn.querySelector('i');
      if (icon) icon.className = 'fa-solid fa-heart';
    }

    pdWishlistBtn.addEventListener('click', (e) => {
      e.preventDefault();
      if (window.toggleWishlist) {
        window.toggleWishlist(product.id);
      }
    });
  }
}

document.addEventListener('DOMContentLoaded', () => {
  initProductDetailsPage();
});
